// Embeds the Inter TTFs as base64 string modules under src/fonts/inter/generated/.
// Idempotent: files are rewritten only when their content changes.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { ROOT } from './_shared.mjs';

const sourceDir = join(ROOT, 'assets', 'fonts', 'inter');
const outDir = join(ROOT, 'src', 'fonts', 'inter', 'generated');

const FONTS = ['Regular', 'Bold', 'Italic'];

// The `: string` annotation keeps the emitted .d.ts tiny instead of inlining the literal.
const HEADER = '// Generated by scripts/generate-inter.mjs, do not edit.\n';

mkdirSync(outDir, { recursive: true });

for (const name of FONTS) {
  const base64 = readFileSync(join(sourceDir, `Inter-${name}.ttf`)).toString('base64');
  const content = `${HEADER}const data: string = '${base64}';\nexport default data;\n`;
  const target = join(outDir, `${name.toLowerCase()}.ts`);
  if (existsSync(target) && readFileSync(target, 'utf8') === content) continue;
  writeFileSync(target, content);
}
